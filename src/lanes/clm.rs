    /// T2(b) — the stub-HTTP wire-shape mapping test: a local listener
    /// answers ONE canned `/v1/systemone` response; the lane must send
    /// the documented request wire (method, path, JSON body shape, option
    /// order) and map the answers back. Wire shape, not scores — the
    /// determinism pin lives at T3 where a real server exists.
    #[test]
    fn stub_http_round_trip_pins_the_request_wire() {
        use std::io::BufRead;
        let listener = std::net::TcpListener::bind(("127.0.0.1", 0)).expect("ephemeral bind");
        let port = listener.local_addr().unwrap().port();
        let handle = std::thread::spawn(move || {
            let (stream, _) = listener.accept().expect("accept");
            let mut reader = std::io::BufReader::new(stream.try_clone().expect("clone"));
            let mut request_line = String::new();
            reader.read_line(&mut request_line).expect("request line");
            assert!(
                request_line.starts_with("POST /v1/systemone HTTP/1.1"),
                "unexpected request line: {request_line}"
            );
            let mut content_length = 0usize;
            loop {
                let mut line = String::new();
                reader.read_line(&mut line).expect("header line");
                let line = line.trim_end();
                if line.is_empty() {
                    break;
                }
                match line.split_once(':') {
                    Some((k, v)) if k.eq_ignore_ascii_case("content-length") => {
                        content_length = v.trim().parse().unwrap_or(0);
                    }
                    _ => {}
                }
            }
            let mut body = vec![0u8; content_length];
            reader.read_exact(&mut body).expect("body");
            let body: Value = serde_json::from_slice(&body).expect("body JSON");
            // The wire shape, asserted at the server side:
            assert_eq!(body["model"], DEFAULT_MODEL);
            assert_eq!(body["temperature"], json!(1.0));
            assert_eq!(body["state"], "fixture state");
            let q = &body["questions"]["pick"];
            assert_eq!(q["type"], "choice");
            assert_eq!(q["instructions"], "pick one");
            assert_eq!(q["criteria"]["0"], "left");
            assert_eq!(q["criteria"]["1"], "right");
            let response = json!({
                "model": DEFAULT_MODEL,
                "answers": {
                    "pick": {"type": "choice", "choice": "1", "confidence": 0.5,
                              "probabilities": {"0": 0.25, "1": 0.75}},
                },
                "usage": {"billing_units": 1, "input_tokens": 128, "output_tokens": 0},
            })
            .to_string();
            drop(reader);
            let mut stream = stream;
            stream
                .write_all(
                    format!(
                        "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n\
                         Content-Length: {}\r\nX-CLM-Latency-Ms: 12.5\r\nConnection: close\r\n\r\n{response}",
                        response.len()
                    )
                    .as_bytes(),
                )
                .expect("respond");
        });

        let lane = ClmLane::from_url(&format!("http://127.0.0.1:{port}"));
        let mut req = DecisionRequest {
            state: "fixture state".into(),
            questions: vec![choice("pick", &["left", "right"])],
        };
        req.questions[0].prompt = "pick one".into();
        let (resp, usage) = lane.decide(&req).expect("round trip");
        handle.join().expect("server thread");
        assert_eq!(resp.answers.len(), 1);
        assert_eq!(resp.answers[0].outcome, Some(Outcome::Choice { index: 1 }));
        assert_eq!(usage.input_tokens, 128);
        assert_eq!(usage.server_ms, Some(12.5));
        assert!(usage.client_ms >= 0.0);
    }

    #[test]
    fn lane_refuses_a_non_200_loudly() {
        use std::io::BufRead;
        let listener = std::net::TcpListener::bind(("127.0.0.1", 0)).expect("bind");
        let port = listener.local_addr().unwrap().port();
        std::thread::spawn(move || {
            let (stream, _) = listener.accept().expect("accept");
            // Drain the request BEFORE responding: closing with unread
            // request bytes in flight sends a TCP RST that kills the
            // client's read (os error 54) instead of delivering the 422.
            let mut reader = std::io::BufReader::new(&stream);
            let mut line = String::new();
            loop {
                line.clear();
                reader.read_line(&mut line).expect("read");
                if line.trim_end().is_empty() {
                    break;
                }
            }
            let mut stream = stream;
            stream
                .write_all(
                    b"HTTP/1.1 422 Unprocessable Entity\r\nContent-Length: 0\r\nConnection: close\r\n\r\n",
                )
                .expect("respond");
        });
        let lane = ClmLane::from_url(&format!("http://127.0.0.1:{port}"));
        let err = lane.decide(&golden_request()).expect_err("422 must be loud");
        assert!(err.0.contains("422"), "unexpected error: {err}");
    }
