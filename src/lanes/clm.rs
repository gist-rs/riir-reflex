/// A mapping failure — fail-closed, never a guessed answer.
#[derive(Debug, Clone, PartialEq)]
pub struct ClmError(pub String);

impl std::fmt::Display for ClmError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "clm lane: {}", self.0)
    }
}

impl std::error::Error for ClmError {}

fn err<T>(msg: impl Into<String>) -> Result<T, ClmError> {
    Err(ClmError(msg.into()))
}

/// Their `confidence()` law: top probability minus the mean of the rest,
/// clamped to `[0, 1]`. Used for a noul answer's confidence (their server
/// does not report one) and as the fallback recomputation for the others.
pub fn confidence(probs: &[f32]) -> f32 {
    if probs.len() < 2 {
        return 1.0;
    }
    let j = probs
        .iter()
        .enumerate()
        .max_by(|a, b| a.1.total_cmp(b.1))
        .map(|(i, _)| i)
        .unwrap_or(0);
    let mut rest = Vec::with_capacity(probs.len() - 1);
    for (i, p) in probs.iter().enumerate() {
        if i != j {
            rest.push(*p);
        }
    }
    let mean = rest.iter().sum::<f32>() / rest.len() as f32;
    (probs[j] - mean).clamp(0.0, 1.0)
}

/// Map their `{"model", "answers": {id: Answer}, "usage"}` body into a
/// [`DecisionResponse`] for `req`, then fail-closed-validate the pair.
///
/// * noul: `{"noul": p_true}` → one probability, `yes = p >= 0.5` (their
///   `label_of` threshold), confidence recomputed by their own law.
/// * choice: `probabilities` in THEIR key order — which is OUR option
///   order by construction (`build_body`'s preserve-order law); a key
///   order drift is an error, never a silent misalignment. Confidence as
///   reported (validated finite + in range).
/// * score: probabilities in level order; the recorded level is their
///   `label_of` argmax.
pub fn map_response(req: &DecisionRequest, body: &Value) -> Result<DecisionResponse, ClmError> {
    let answers = body
        .get("answers")
        .and_then(Value::as_object)
        .ok_or_else(|| ClmError("response has no answers object".into()))?;
    let mut out = Vec::with_capacity(req.questions.len());
    for q in &req.questions {
        let a = answers
            .get(&q.id)
            .ok_or_else(|| ClmError(format!("response missing answer for question {}", q.id)))?;
        let answer = match q.kind {
            QuestionKind::Noul => {
                let p = a
                    .get("noul")
                    .and_then(Value::as_f64)
                    .ok_or_else(|| ClmError(format!("noul answer {} missing `noul`", q.id)))?;
                let p = p as f32;
                if !(0.0..=1.0).contains(&p) {
                    return err(format!("noul answer {} probability {p} outside [0, 1]", q.id));
                }
                Answer {
                    question_id: q.id.clone(),
                    outcome: Some(Outcome::Noul { yes: p >= 0.5 }),
                    probabilities: vec![p],
                    confidence: confidence(&[1.0 - p, p]),
                }
            }
            QuestionKind::Choice | QuestionKind::Score => {
                let dist = a
                    .get("probabilities")
                    .and_then(Value::as_object)
                    .ok_or_else(|| {
                        ClmError(format!("answer {} missing probabilities object", q.id))
                    })?;
                let (keys, _texts) = candidates(q);
                if dist.len() != keys.len() {
                    return err(format!(
                        "answer {} has {} probabilities for {} options",
                        q.id,
                        dist.len(),
                        keys.len()
                    ));
                }
                // THEIR key order is OUR option order — drift is an error.
                let mut probs = Vec::with_capacity(keys.len());
                for key in &keys {
                    let p = dist.get(key).and_then(Value::as_f64).ok_or_else(|| {
                        ClmError(format!("answer {} key {key} missing/misordered", q.id))
                    })?;
                    let p = p as f32;
                    if !(0.0..=1.0).contains(&p) {
                        return err(format!("answer {} probability {p} outside [0, 1]", q.id));
                    }
                    probs.push(p);
                }
                let confidence = match a.get("confidence").and_then(Value::as_f64) {
                    Some(c) => {
                        let c = c as f32;
                        if !c.is_finite() || !(0.0..=1.0).contains(&c) {
                            return err(format!("answer {} confidence {c} outside [0, 1]", q.id));
                        }
                        c
                    }
                    None => confidence(&probs),
                };
                let top = probs
                    .iter()
                    .enumerate()
                    .max_by(|x, y| x.1.total_cmp(y.1))
                    .map(|(i, _)| i)
                    .unwrap_or(0) as u32;
                let outcome = match q.kind {
                    QuestionKind::Choice => Outcome::Choice { index: top },
                    _ => Outcome::Score { level: top },
                };
                Answer {
                    question_id: q.id.clone(),
                    outcome: Some(outcome),
                    probabilities: probs,
                    confidence,
                }
            }
        };
        out.push(answer);
    }
    let response = DecisionResponse {
        answers: out,
        routing: Routing {
            lane: Lane::Clm,
            reason: Some(format!("external comparison lane ({DEFAULT_MODEL} over /v1/systemone)")),
        },
        calibration: Calibration::none(),
    };
    response
        .validate_against(req)
        .map_err(|e| ClmError(format!("mapped response fails the wire contract: {e}")))?;
    Ok(response)
}

