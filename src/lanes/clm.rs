/// Their `to_text` (`schema.py`): a state / description that may be a
/// string, object or array rendered as plain text — the heads are trained
/// on prose, not on JSON.
pub fn to_text(x: &Value) -> String {
    to_text_indent(x, 0)
}

fn to_text_indent(x: &Value, indent: usize) -> String {
    match x {
        // None → ""; str → as-is.
        Value::Null => String::new(),
        Value::String(s) => s.clone(),
        // bool BEFORE number (Python's isinstance order; disjoint in Rust).
        Value::Bool(b) => if *b { "true" } else { "false" }.to_string(),
        Value::Number(n) => render_number(n),
        Value::Object(map) => {
            let pad = " ".repeat(indent);
            let parts: Vec<String> = map
                .iter()
                .map(|(k, v)| match container(v) {
                    // Non-empty containers break onto their own indented block.
                    Some(true) => format!("{pad}{k}:\n{}", to_text_indent(v, indent + 2)),
                    _ => format!("{pad}{k}: {}", to_text_indent(v, 0)),
                })
                .collect();
            // Top-level fields blank-line separated; nested ones single-newline.
            if indent == 0 { parts.join("\n\n") } else { parts.join("\n") }
        }
        Value::Array(items) => {
            let pad = " ".repeat(indent);
            let parts: Vec<String> = items
                .iter()
                .map(|v| match container(v) {
                    Some(true) => format!("{pad}-\n{}", to_text_indent(v, indent + 2)),
                    _ => format!("{pad}- {}", to_text_indent(v, 0)),
                })
                .collect();
            parts.join("\n")
        }
    }
}

/// `Some(non_empty)` when `v` is a dict/list — their `isinstance(v, (dict,
/// list)) and v` branch; `None` for scalars. The emptiness decides whether
/// a value renders as `key: value` / `- item` or breaks onto a block.
fn container(v: &Value) -> Option<bool> {
    match v {
        Value::Object(m) => Some(!m.is_empty()),
        Value::Array(a) => Some(!a.is_empty()),
        _ => None,
    }
}

/// Their `str(x)` over a JSON number. Integers are positional; floats get
/// Python's `repr` presentation (shortest round-trip digits, `.0` on
/// integral values, exponential outside `[1e-4, 1e16)` with a signed
/// two-digit exponent).
fn render_number(n: &serde_json::Number) -> String {
    if let Some(i) = n.as_i64() {
        return i.to_string();
    }
    if let Some(u) = n.as_u64() {
        return u.to_string();
    }
    if let Some(i) = n.as_i128() {
        return i.to_string();
    }
    if let Some(u) = n.as_u128() {
        return u.to_string();
    }
    match n.as_f64() {
        Some(f) => py_float(f),
        // serde_json can no longer represent it — their Python would keep
        // arbitrary precision; we render the raw text form as the least
        // surprising fallback.
        None => n.to_string(),
    }
}

/// Python `repr(float)`: shortest round-trip digits, then the presentation
/// rule (`-4 <= adj < 16` fixed, else exponential `d[.ddd]e±XX`).
fn py_float(v: f64) -> String {
    if v.is_nan() {
        return "nan".to_string();
    }
    if v.is_infinite() {
        return if v > 0.0 { "inf" } else { "-inf" }.to_string();
    }
    // Rust's LowerExp gives the shortest round-trip digits: `d[.ddd]e<exp>`.
    let sci = format!("{:e}", v);
    let (mantissa, exp) = sci.split_once('e').unwrap_or((sci.as_str(), "0"));
    let adj: i32 = exp.parse().unwrap_or(0);
    let (neg, mantissa) = match mantissa.strip_prefix('-') {
        Some(m) => (true, m),
        None => (false, mantissa),
    };
    let digits: String = mantissa.chars().filter(|c| *c != '.').collect();
    // `adj` = floor(log10(|v|)) = the exponent of the leading digit.
    let body = if adj >= 0 {
        // Fixed notation (adj < 16, Python's rule): decimal point after
        // adj+1 digits, right-padded when the digits stop short (1e15).
        if adj < 16 {
            let point = (adj + 1) as usize;
            let mut int_part: String = digits.chars().take(point).collect();
            let frac_part: String = digits.chars().skip(point).collect();
            while int_part.len() < point {
                int_part.push('0');
            }
            if frac_part.is_empty() {
                format!("{int_part}.0")
            } else {
                format!("{int_part}.{frac_part}")
            }
        } else {
            exponential(&digits, adj)
        }
    } else if adj >= -4 {
        // Sub-unity fixed notation: `0.` + the zeros the exponent implies
        // + the digits (1e-4 → 0.0001).
        format!("0.{}{}", "0".repeat((-adj - 1) as usize), digits)
    } else {
        exponential(&digits, adj)
    };
    if neg { format!("-{body}") } else { body }
}

/// The exponential branch: `d[.ddd]e±XX` (sign always, exponent ≥ 2 digits).
fn exponential(digits: &str, adj: i32) -> String {
    let mant = if digits.len() == 1 {
        digits.to_string()
    } else {
        format!("{}.{}", &digits[..1], &digits[1..])
    };
    format!("{mant}e{}{:02}", if adj < 0 { '-' } else { '+' }, adj.abs())
}

/// Their `state_text`: context first, question last, blank-line separated;
/// the shorter side survives alone; both stripped.
pub fn state_text(state: &Value, instructions: &Value) -> String {
    let s = to_text(state);
    let s = s.trim();
    let i = to_text(instructions);
    let i = i.trim();
    if !s.is_empty() && !i.is_empty() {
        format!("{s}\n\n{i}")
    } else {
        format!("{s}{i}")
    }
}

/// `(option keys in answer order, candidate text per option)` for one of
/// OUR questions — their `candidates()` law applied at the adapter seam.
///
/// * `noul`: keys `["false", "true"]` (false FIRST — the answer order the
///   distribution maps onto). Our wire cannot carry their per-side
///   descriptions, so the default law always applies: `"No. This is
///   false: {instructions}"` / `"Yes. This is true: {instructions}"`,
///   or the bare key when the prompt is empty.
/// * `choice`: keys are the option POSITIONS (`"0"`, `"1"`, … — the
///   answer's index maps straight back to [`Outcome::Choice`]); the
///   candidate text is the option's own text, or the key when the option
///   is empty (their `crit[k] in (None, "")` law — "nothing is prefixed,
///   so a candidate reaches the encoder exactly as the caller wrote it").
/// * `score`: keys are the level positions; the text is each rubric level.
pub fn candidates(q: &Question) -> (Vec<String>, Vec<String>) {
    let ins = q.prompt.trim().to_string();
    match q.kind {
        QuestionKind::Noul => {
            let texts = if ins.is_empty() {
                NOUL_KEYS.iter().map(|k| format!("{k}: {k}")).collect()
            } else {
                vec![
                    format!("false: No. This is false: {ins}"),
                    format!("true: Yes. This is true: {ins}"),
                ]
            };
            (NOUL_KEYS.iter().map(|k| k.to_string()).collect(), texts)
        }
        QuestionKind::Choice | QuestionKind::Score => {
            let keys: Vec<String> = (0..q.options.len()).map(|i| i.to_string()).collect();
            let texts = q
                .options
                .iter()
                .enumerate()
                .map(|(i, o)| {
                    if o.is_empty() {
                        i.to_string()
                    } else {
                        o.clone()
                    }
                })
                .collect();
            (keys, texts)
        }
    }
}

/// The `instructions` the request carries for one question: the prompt,
/// with the optional criteria prose folded under it (single newline — the
/// blank-line law separates CONTEXT from QUESTION at [`state_text`]'s
/// level; prompt and criteria are one logical question here).
fn instructions_of(q: &Question) -> String {
    match &q.criteria {
        Some(c) if !c.trim().is_empty() => format!("{}\n{}", q.prompt, c),
        _ => q.prompt.clone(),
    }
}

// ─────────────────────────────────────────────────────── the request wire

/// Build their `POST /v1/systemone` body from a [`DecisionRequest`].
///
/// `{"state": .., "model": "clm-latest", "questions": {id: {type,
/// instructions, criteria?}}, "temperature": 1.0}` — the TypeSafe shape
/// their `schema.py` docstring pins. `serde_json` runs with
/// `preserve_order`, so a choice's `criteria` object keeps OUR option
/// order — the order their `list(crit)` reads, and the order the answer
/// distribution maps back onto (parity-critical).
pub fn build_body(req: &DecisionRequest) -> Value {
    let mut questions = Map::new();
    for q in &req.questions {
        let mut qj = Map::new();
        qj.insert("type".into(), json!(q.kind.as_str()));
        qj.insert("instructions".into(), json!(instructions_of(q)));
        match q.kind {
            // No criteria: their `crit or {}` default-candidates law applies.
            QuestionKind::Noul => {}
            QuestionKind::Choice => {
                let mut criteria = Map::new();
                for (i, o) in q.options.iter().enumerate() {
                    criteria.insert(i.to_string(), json!(o));
                }
                qj.insert("criteria".into(), Value::Object(criteria));
            }
            QuestionKind::Score => {
                qj.insert("criteria".into(), json!(q.options));
            }
        }
        questions.insert(q.id.clone(), Value::Object(qj));
    }
    json!({
        "state": req.state,
        "model": DEFAULT_MODEL,
        "questions": Value::Object(questions),
        "temperature": 1.0,
    })
}

