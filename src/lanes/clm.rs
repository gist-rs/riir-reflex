//! The CLM comparison lane (Issue 019; Apache-2.0, not affiliated).
//!
//! Two halves, both pinned to the reference tree at sha `cca045ff`
//! (`Contrastive-LM/CLM`, `src/clm/schema.py` + `server.py`):
//!
//! 1. **The prose-rendering law** ([`to_text`] / [`state_text`] /
//!    [`candidates`]) — "the layout the heads were trained on". Objects
//!    render as `key: value` fields (top-level fields blank-line
//!    separated, nested ones indented), arrays as `- item` lines, key
//!    order preserved. The law is copied BYTE-FOR-BYTE from their Python
//!    (including Python's float `str()` presentation and the trailing
//!    spaces on empty values) — a drift here reads as silent score drift,
//!    never as an error. Every fixture in the tests below is a golden
//!    generated by running THEIR code at the pin (`.raw/clm_goldens.py`,
//!    the offline one-time carve-out — no Python in our tree).
//!
//! 2. **The `/v1/systemone` HTTP adapter** ([`ClmLane`]) — their stack
//!    serves (vLLM Qwen3-8B pooling + `clm-serve` heads), our Rust
//!    measures. Thin localhost HTTP client over std (`serve.rs`'s
//!    hand-rolled posture; no new deps), request built from a
//!    [`DecisionRequest`], response mapped into a
//!    [`DecisionResponse`] with distribution + confidence columns and NO
//!    abstain mapping (CLM has none — the inherited Jev flaw; the wire's
//!    abstain stays first-class for OUR lanes).
//!
//! Deliberate divergences from the reference (each documented where it
//! happens): the wire cannot carry their per-side noul descriptions (a
//! single `criteria: Option<String>` cannot express `{"true": ..,
//! "false": ..}`), so a noul question always uses their default
//! candidates; the choice/score `instructions` fold the optional
//! criteria prose under the prompt; the temperature is pinned at 1.0
//! (their `temperature ∈ (0, 100]` DIVIDES logits — never our τ
//! vocabulary); a noul answer's confidence is not reported by their
//! server, so we compute their own `top − mean(rest)` law over the two
//! probabilities.

