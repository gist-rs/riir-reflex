    #[test]
    fn candidates_match_the_reference_goldens() {
        // noul default law, both prompt states.
        let (keys, texts) = candidates(&noul("q", "Is the sky blue?"));
        assert_eq!(keys, ["false", "true"]);
        assert_eq!(
            texts,
            [
                "false: No. This is false: Is the sky blue?",
                "true: Yes. This is true: Is the sky blue?"
            ]
        );
        let (keys, texts) = candidates(&noul("q", ""));
        assert_eq!(keys, ["false", "true"]);
        assert_eq!(texts, ["false: false", "true: true"]);
        // choice: empty option → its key (their `crit[k] in (None, "")`
        // law; the golden carries {"move": "walk left", "jump": "",
        // "stay": None}).
        let (keys, texts) = candidates(&choice("q", &["walk left", "", "stay"]));
        assert_eq!(keys, ["0", "1", "2"]);
        // Only the EMPTY option falls back to its key; non-empty text stays
        // verbatim (their golden: {"move": "walk left", "jump": "",
        // "stay": None} → ["walk left", "jump", "stay"]).
        assert_eq!(texts, ["walk left", "1", "stay"]);
        // score: positional keys, levels verbatim.
        let (keys, texts) = candidates(&score("q", &["bad", "meh", "great"]));
        assert_eq!(keys, ["0", "1", "2"]);
        assert_eq!(texts, ["bad", "meh", "great"]);
    }

    #[test]
