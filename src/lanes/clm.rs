        // The golden `pairs` case, replayed through the adapter: the state
        // renders `ticket: 4711\n\nsys: safari` + the question; the choice
        // criteria carry positions 0/1 in OUR order.
        let req = DecisionRequest {
            state: obj(&[("ticket", s("4711")), ("sys", s("safari"))]).to_string(),
            questions: vec![
                Question::choice(
                    "q1",
                    "Which subsystem?",
                    vec!["auth".into(), "session".into()],
                    None,
                ),
                noul("q2", "Reproducible?"),
            ],
        };
        let body = build_body(&req);
        assert_eq!(body["state"], req.state);
        assert_eq!(body["model"], DEFAULT_MODEL);
        assert_eq!(body["temperature"], json!(1.0));
        let q1 = &body["questions"]["q1"];
        assert_eq!(q1["type"], "choice");
        assert_eq!(q1["instructions"], "Which subsystem?");
        // preserve_order: the serialized criteria object must read
